public class Character {

    //fields
    private String name;
    private int health;
    private int attack;
    private int defense;
    private boolean isFainted;

    //constructor
    Character(String n, int hp, int atk, int def, boolean faint) {
        n = name;
        hp = health;
        atk = attack;
        def = defense;
        faint = isFainted;
    }

}
